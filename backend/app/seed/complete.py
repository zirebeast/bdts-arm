def pe_data(sec: dict, vid: str, eo, rnd: random.Random, flaw: bool = False, opo_reg: str = "—") -> dict:
    """Полностью заполненный раздел полевого этапа с разбросом значений; flaw — отклонения «на границе допуска» для ЕО, направляемой на ЭПБ."""
    d = build_sec_data(sec, True)
    code, kind = sec["code"], sec["kind"]
    inst = INSTRUMENTS.get(sec.get("instrument", ""))
    if inst:
        d["serial"] = inst[0]
    if code == "doc":
        f, m, y = (eo.factory_number if eo else "") or "0000", ((eo.model if eo else "") or "ТУ").split()[0], 2021
        opo = opo_reg
        rows = DOC_ROWS.get(vid, DOC_ROWS["vessel"])
        d["rows"] = [{"id": i, "type": tp, "no": no.format(f=f, m=m, y=y, opo=opo), "st": "Предоставлен"} for i, (tp, no) in enumerate(rows)]
        d["values"] = {"nadzor": "Отсутствуют", "avar": "Отсутствуют", "rem": "Не проводился", "res": "Документация соответствует объёму работ",
                       "fin": "Допускается к дальнейшей эксплуатации"}
    elif kind == "checklist":
        d["items"] = {c: (sec.get("sampleItems") or {}).get(c, 0) for c, *_ in sec["items"]}
        if flaw:
            first = sec["items"][0][0]
            d["items"][first] = 1
        d["notes"] = {}
        for c, _n, op in sec["items"]:
            v = op[d["items"][c]][0]
            if v in NOTE:
                d["notes"][c] = NOTE[v]
    elif kind == "points":
        for ei, el in enumerate(d["elements"]):
            cfg = sec["elements"][ei]
            for k, p in enumerate(el["points"]):
                if sec["mode"] == "thk":
                    s = float(cfg["s"])
                    nd = 2 if s < 20 else 1
                    x = round(float(p["value"] or s * 1.2) * rnd.uniform(0.975, 1.025), nd)
                    if flaw and ei == len(d["elements"]) // 2 and k == 1:
                        x = round(s * 1.05, nd)  # на границе допуска (≤ 1,08·s)
                    elif tol_thk(x, s) != "ok":
                        x = round(s * rnd.uniform(1.10, 1.22), nd)
                    p["value"] = _fmt(x, nd)
                else:
                    lo, hi = cfg.get("lo", sec.get("lo", 120)), cfg.get("hi", sec.get("hi", 180))
                    x = float(p["value"] or (lo + hi) / 2) + rnd.randint(-6, 6)
                    if tol_hb(x, lo, hi) != "ok":
                        x = rnd.randint(int(lo) + 12, int(hi) - 12)
                    p["value"] = str(int(x))
    elif kind == "table":
        rows = [copy.deepcopy(r) for r in sec.get("sample", [])] + copy.deepcopy(EXTRA_ROWS.get((vid, code), []))
        for r in rows:
            for c in sec["cols"]:
                if c["type"] == "num" and str(r.get(c["key"], "")).strip() not in ("", "—"):
                    try:
                        v = float(str(r[c["key"]]).replace(",", "."))
                        r[c["key"]] = _fmt(v * rnd.uniform(0.92, 1.08), 2 if abs(v) < 2 else 1) if c["key"] not in ("vol", "plan", "fact") else r[c["key"]]
                    except ValueError:
                        pass
            if tol_row(sec["tol"], r) != "ok":
                _fix_row(sec["tol"], r, rnd)
        d["rows"] = [{"id": i, **r} for i, r in enumerate(rows)]
    for f in sec.get("fields", []):
        if code == "doc":
            break
        v = d["values"].get(f["key"], "")
        if f.get("tol") and f["tol"]["t"] == "map":
            v = _ok_key(f["tol"]["m"])
        elif f["type"] == "select" and not v:
            v = f["opts"][0]
        elif f["type"] == "num" and not v:
            v = {"dp": "0.02", "leak": "0"}.get(f["key"], "")
            if code == "spectral":
                v = SPECTRAL.get(eo.steel_grade if eo else "", SPECTRAL["09Г2С"]).get(f["key"], "")
        if code == "spectral" and f["key"] == "steel" and eo and eo.steel_grade in f["opts"]:
            v = eo.steel_grade
        if code == "functional" and f["key"] == "p":
            v = _fmt(rnd.uniform(5.2, 5.9))
        if code == "functional" and f["key"] == "t":
            v = str(rnd.randint(32, 47))
        d["values"][f["key"]] = v
    d["concl"] = PE_CONCL.get(code, "Контроль выполнен в полном объёме, результаты в протоколе")
    if flaw and code in ("uzt", "vik"):
        d["concl"] = "Выявлены отклонения на границе допуска; рекомендуется ЭПБ" if code == "uzt" else "Выявлена поверхностная коррозия обечайки без утонения за пределы допуска"
    return d


def kp_data(sec: dict, vid: str, eo, pe: dict, rnd: random.Random, end: date, flaw: bool = False) -> dict:
    """Разделы КП: расчёт ресурса по фактическим толщинам (из УЗТ), перечень работ, НТД, заключение о ТС со сроком следующего ДО."""
    d = build_sec_data(sec, True)
    code = sec["code"]
    uzt = pe.get("uzt")
    margins = []
    if uzt:
        for ei, el in enumerate(uzt[1]["elements"]):
            s = float(uzt[0]["elements"][ei]["s"])
            vals = [float(p["value"]) for p in el["points"] if p["value"]]
            if vals:
                margins.append((el["name"], min(vals), s))
    rate = round(rnd.uniform(0.04, 0.07), 3)
    rt = min(((mn - s) / rate for _n, mn, s in margins), default=12.0)
    rt = round(min(rt, 25.0), 1)
    if flaw:
        rt = round(min(rt, 6.0), 1)
    if code == "calc":
        vals = {"vc": _fmt(rate, 3), "st": _fmt(min((mn for _n, mn, _s in margins), default=10.0), 2), "rt": _fmt(rt), "phi": "1.0", "c": "1.5",
                "el": min(margins, key=lambda x: x[1] - x[2])[0] if margins else "Корпус"}
        d["values"] = {f["key"]: vals.get(f["key"], f.get("v", "")) for f in sec.get("fields", [])}
        d["values"].setdefault("vc", vals["vc"])  # скорость коррозии, принятая в расчёте (для приложения «Расчет на прочность»)
    elif code == "conclusion":
        years = max(1, min(4, int(rt // 2)))
        nxt = date(end.year + years, end.month, min(end.day, 28))
        ts = "Работоспособное" if flaw or rnd.random() < 0.6 else "Исправное"
        name = eo.name if eo else "Объект"
        text = {"vessel": f"{name} допускается к дальнейшей эксплуатации на рабочих параметрах (P раб. 6,3 МПа, T раб. 60 °C) до срока следующего ТД. "
                          "Компенсирующие мероприятия: восстановить АКП в зонах локальных нарушений; при следующем ТД выполнить контроль толщины в зонах минимальных значений.",
                "tpa": f"{name} допускается к дальнейшей эксплуатации при PN 8,0 МПа. Рекомендуется: восстановление АКП, контроль герметичности затвора при плановом ТО.",
                "wellhead": f"{name} допускается к дальнейшей эксплуатации при рабочем давлении 21 МПа. Рекомендуется: подтяжка шпилек фланцевых соединений, "
                            "восстановление АКП, ревизия задвижки с заеданием хода шпинделя.",
                "grs": f"{name} допускается к дальнейшей эксплуатации в составе ГРС. Рекомендуется: устранение нарушений изоляционного покрытия, "
                       "контроль вибрации трубопровода после регулятора при плановом ТО."}.get(vid, "Объект допускается к дальнейшей эксплуатации.")
        if flaw:
            text = (f"{name} допускается к эксплуатации до проведения экспертизы промышленной безопасности. Выявлены отклонения толщины стенки на границе допуска; "
                    "необходимо провести ЭПБ с уточнённым расчётом на прочность, до её завершения — контроль параметров эксплуатации ежесменно.")
        d["values"] = {"ts": ts, "next": nxt.isoformat(), "text": text}
    elif code == "work_scope":
        n_pts = sum(len(el["points"]) for el in uzt[1]["elements"]) if uzt else 0
        if vid == "vessel":
            d["rows"] = [{"id": 0, "w": "УЗТ, точек", "plan": str(n_pts), "fact": str(n_pts)}, {"id": 1, "w": "УЗК швов, м", "plan": "12", "fact": "12"},
                         {"id": 2, "w": "Твёрдость, точек", "plan": "6", "fact": "6"}, {"id": 3, "w": "МПК, зон", "plan": "3", "fact": "3"}]
    return d


def fill_result(template: dict, vid: str, eos: list, seed: int, end: date, flaw_idx: int | None = None, opo_reg: str = "—") -> dict[tuple[int, str], dict]:
    """Данные всех разделов результата ДО по каждой ЕО: {(eo_idx, code): data}."""
    out = {}
    for i, eo in enumerate(eos):
        rnd = random.Random(seed * 100 + i)
        flaw = flaw_idx == i
        pe = {}
        for s in template["sections"]:
            if s["kind"] == "info" or s["stage"] != "ПЭ":
                continue
            d = pe_data(s, vid, eo, rnd, flaw, opo_reg)
            pe[s["code"]] = (s, d)
            out[(i, s["code"])] = d
        for s in template["sections"]:
            if s["kind"] == "info" or s["stage"] != "КП":
                continue
            out[(i, s["code"])] = kp_data(s, vid, eo, pe, rnd, end, flaw)
    return out

