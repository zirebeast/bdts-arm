def _fmt(x: float, d: int = 1) -> str:
    return f"{x:.{d}f}"


def _ok_key(m: dict) -> str:
    return next(k for k, v in m.items() if v == "ok")


def _fix_row(spec: dict, row: dict, rnd: random.Random):
    t = spec["t"]
    if t == "col":
        row[spec["c"]] = _ok_key(spec["m"])
    elif t == "cols":
        for c, m in spec["cs"]:
            if m.get(row.get(c)) != "ok":
                row[c] = _ok_key(m)
    elif t == "vol_col":
        row[spec["vol"]] = str(max(int(float(row.get(spec["vol"]) or 0)), spec["min"] + rnd.randint(0, 10)))
        row[spec["c"]] = _ok_key(spec["m"])
    elif t == "bands":
        row[spec["c"]] = _fmt(rnd.uniform(1.2, spec["warn"] * 0.85))
    elif t == "abs_bands":
        row[spec["c"]] = str(rnd.randint(3, int(spec["warn"] * 0.7)))
    elif t == "range":
        row[spec["c"]] = _fmt(rnd.uniform(spec["lo"] + 0.05, spec["hi"] - 0.05), 2)
    elif t == "plan_fact":
        row["fact"] = row.get("plan", "")
    elif t == "doc":
        row["st"] = "Предоставлен"


